/**
 * Writes src-tauri/capabilities/home-writes-<platform>.json: where plugin-fs
 * may create, change and remove files for the window.
 *
 *   bun apps/client/scripts/write-home-writes-capabilities.ts
 *
 * The window reads the whole home folder but does not write to the places a
 * program starts from at login: `Library` (macOS), `AppData` and the
 * PowerShell profile folders (Windows), and every dot entry at the top of
 * home except `.pile` (shell profiles, `.ssh`, `.config`). A script that got
 * into the window (one sanitizer bug is enough) must not be able to plant
 * something that runs later.
 *
 * A deny always beats an allow in a Tauri scope, and a scope is a glob, so
 * "every dot name except .pile" is spelled out as the names that differ from
 * it at each letter. Letters are matched in both cases: the default macOS and
 * Windows file systems ignore case, the glob does not.
 *
 * The same rule for the app's own commands is `is_protected` in
 * src-tauri/src/paths.rs; `capabilities.rs` there tests these files against
 * the glob crate Tauri uses. Change all three together.
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

/** plugin-fs commands that create, change or remove something */
const WRITE_PERMISSIONS = [
	'fs:allow-remove',
	'fs:allow-rename',
	'fs:allow-mkdir',
	'fs:allow-write-text-file',
	'fs:allow-write-file',
	'fs:allow-copy-file',
]

const either_case = (name: string) =>
	[...name].map(char => (/[a-z]/i.test(char) ? `[${char.toUpperCase()}${char.toLowerCase()}]` : char)).join('')

/** Every name that starts with a dot, except `.pile` in any letter case. */
function dot_names_except_pile(): string[] {
	const keep = 'pile'
	const names: string[] = []
	for (let index = 0; index < keep.length; index++) {
		const same = either_case(keep.slice(0, index))
		const letter = keep[index]!
		// differs at this letter, whatever follows
		names.push(`.${same}[!${letter.toUpperCase()}${letter.toLowerCase()}]*`)
		// stops before this letter: `.p`, `.pi`, `.pil`
		if (index > 0) names.push(`.${same}`)
	}
	// goes on after the last letter: `.pilex`, `.pile.bak`
	names.push(`.${either_case(keep)}?*`)
	return names
}

/** The entry itself and everything below it. */
const with_contents = (path: string) => [{ path }, { path: `${path}/**` }]

const DOT_ENTRIES = dot_names_except_pile().flatMap(name => with_contents(`$HOME/${name}`))

const PLATFORMS = {
	macos: {
		platform: 'macOS',
		deny: [...with_contents(`$HOME/${either_case('Library')}`), ...DOT_ENTRIES],
	},
	windows: {
		platform: 'windows',
		deny: [
			...with_contents(`$HOME/${either_case('AppData')}`),
			...with_contents(`$DOCUMENT/${either_case('PowerShell')}`),
			...with_contents(`$DOCUMENT/${either_case('WindowsPowerShell')}`),
			...DOT_ENTRIES,
		],
	},
	linux: {
		platform: 'linux',
		deny: DOT_ENTRIES,
	},
}

for (const [name, { platform, deny }] of Object.entries(PLATFORMS)) {
	const capability = {
		$schema: '../gen/schemas/desktop-schema.json',
		identifier: `home-writes-${name}`,
		description:
			'Where the window may create, change and remove files: the home folder without the places a program starts from at login. Generated by scripts/write-home-writes-capabilities.ts — edit that, not this file.',
		windows: ['main'],
		platforms: [platform],
		permissions: WRITE_PERMISSIONS.map(identifier => ({
			identifier,
			allow: [{ path: '$HOME' }, { path: '$HOME/**/*' }],
			deny,
		})),
	}
	const file = fileURLToPath(new URL(`../src-tauri/capabilities/home-writes-${name}.json`, import.meta.url))
	writeFileSync(file, `${JSON.stringify(capability, null, '\t')}\n`)
	console.log(`wrote ${file}`)
}
